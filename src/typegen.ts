import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { BUILTIN_ENV_VARS } from "./analyzer.js";
import type { AuditResult } from "./types.js";

/**
 * Generates TypeScript ambient declarations (`env.d.ts`) from an AuditResult.
 */
export function generateEnvTypes(result: AuditResult): string {
  const processKeys = new Set<string>();
  const importMetaKeys = new Set<string>();

  for (const [key, refs] of Object.entries(result.usedInCode)) {
    if (BUILTIN_ENV_VARS.has(key)) continue;

    for (const ref of refs) {
      if (ref.source === "import.meta.env") {
        importMetaKeys.add(key);
      } else {
        processKeys.add(key);
      }
    }
  }

  // Also include unused keys from .env.example as process.env keys if not already categorized
  for (const key of result.unusedInExample) {
    if (!BUILTIN_ENV_VARS.has(key) && !importMetaKeys.has(key)) {
      processKeys.add(key);
    }
  }

  const lines: string[] = [
    "// Auto-generated by env-drift. Do not edit manually.",
    "",
  ];

  const sortedProcess = Array.from(processKeys).sort();
  if (sortedProcess.length > 0) {
    lines.push("declare namespace NodeJS {");
    lines.push("  interface ProcessEnv {");
    for (const key of sortedProcess) {
      lines.push(`    ${key}: string;`);
    }
    lines.push("  }");
    lines.push("}");
    lines.push("");
  }

  const sortedMeta = Array.from(importMetaKeys).sort();
  if (sortedMeta.length > 0) {
    lines.push("interface ImportMetaEnv {");
    for (const key of sortedMeta) {
      lines.push(`  readonly ${key}: string;`);
    }
    lines.push("}");
    lines.push("");
    lines.push("interface ImportMeta {");
    lines.push("  readonly env: ImportMetaEnv;");
    lines.push("}");
    lines.push("");
  }

  if (sortedProcess.length === 0 && sortedMeta.length === 0) {
    lines.push("// No environment variables detected.");
    lines.push("");
  }

  return lines.join("\n");
}

/**
 * Writes the generated `env.d.ts` file to disk.
 */
export function writeEnvTypes(
  outputPath: string,
  result: AuditResult
): { outputPath: string; count: number } {
  const content = generateEnvTypes(result);
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, content, "utf-8");

  const uniqueKeys = new Set([
    ...Object.keys(result.usedInCode).filter((k) => !BUILTIN_ENV_VARS.has(k)),
    ...result.unusedInExample.filter((k) => !BUILTIN_ENV_VARS.has(k)),
  ]);

  return { outputPath, count: uniqueKeys.size };
}
